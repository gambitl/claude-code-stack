"""Print INVENTORY.md: a readable summary of my Claude Code setup.

It reads ~/.claude (path given as the first argument) and ~/.claude.json.
The output is regenerated on every sync, so it is never edited by hand.
"""

import datetime
import json
import os
import sys

src = sys.argv[1]
home = os.path.expanduser("~")

# Every file read below is UTF-8, and so is this script's output. Windows
# would otherwise assume the local code page and fail on the accents and
# dashes that the skill descriptions contain.
sys.stdout.reconfigure(encoding="utf-8")


def load(path, default):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (FileNotFoundError, NotADirectoryError):
        return default


def skill_description(skill_md):
    """Return the description line from a SKILL.md front matter, or ''."""
    try:
        with open(skill_md, encoding="utf-8") as f:
            lines = f.read().split("\n")
    except FileNotFoundError:
        return ""
    if not lines or lines[0].strip() != "---":
        return ""
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if line.startswith("description:"):
            return line[len("description:"):].strip().strip("\"'")
    return ""


settings = load(os.path.join(src, "settings.json"), {})
installed = load(os.path.join(src, "plugins", "installed_plugins.json"), {})
installed = installed.get("plugins", installed)
user_mcp = load(os.path.join(home, ".claude.json"), {}).get("mcpServers", {})

out = []
w = out.append

w("# Inventory of my Claude Code setup")
w("")
w(f"Generated by `sync.sh` on {datetime.date.today().isoformat()}. "
  "Do not edit this file by hand, because the next sync overwrites it.")
w("")

w("## Main settings")
w("")
w(f"- Model: `{settings.get('model', 'default')}`")
w(f"- Effort level: `{settings.get('effortLevel', 'default')}`")
for model, extra in settings.get("modelSettings", {}).items():
    if "effortLevel" in extra:
        w(f"- Effort level for `{model}`: `{extra['effortLevel']}`")
mode = settings.get("permissions", {}).get("defaultMode", "default")
w(f"- Default permission mode: `{mode}`")
allow = settings.get("permissions", {}).get("allow", [])
w(f"- Number of always-allowed permission rules: {len(allow)}")
if settings.get("statusLine"):
    w(f"- Status line command: `{settings['statusLine'].get('command', '')}`")
w("")

w("## Hooks")
w("")
w("Hooks are shell commands that Claude Code runs automatically at "
  "specific moments, called events. They are defined in "
  "`config/settings.json`.")
w("")
for event, groups in settings.get("hooks", {}).items():
    w(f"### {event}")
    w("")
    for group in groups:
        matcher = group.get("matcher")
        when = (f"Runs when the tool name matches `{matcher}`."
                if matcher and matcher != "*" else "Runs every time.")
        for hook in group.get("hooks", []):
            w(when)
            w("")
            w("```sh")
            w(hook.get("command", hook.get("prompt", "")))
            w("```")
            w("")

w("## Plugins")
w("")
w("A plugin bundles skills, agents, hooks or MCP servers that someone else "
  "maintains. These are the plugins turned on for my user account.")
w("")
for plugin, enabled in sorted(settings.get("enabledPlugins", {}).items()):
    versions = [i.get("version", "?") for i in installed.get(plugin, [])
                if i.get("scope") == "user"]
    version = versions[0] if versions else "?"
    state = "on" if enabled else "off"
    w(f"- `{plugin}`, version `{version}`, {state}")
w("")

w("## MCP servers")
w("")
w("MCP servers give Claude Code extra tools, such as access to Linear or "
  "GitHub. Plugins and claude.ai connectors can add more servers that are "
  "not listed here.")
w("")
for name, config in sorted(user_mcp.items()):
    kind = config.get("type", "stdio")
    w(f"- `{name}` ({kind}), declared in `~/.claude.json`")
for name, config in sorted(settings.get("mcpServers", {}).items()):
    kind = config.get("type", "stdio")
    w(f"- `{name}` ({kind}), declared in `settings.json`")
w("")

w("## Skills")
w("")
w("A skill is a folder with a `SKILL.md` file of instructions that Claude "
  "loads when a task matches it.")
w("")
w("### My own skills (copied into `skills/`)")
w("")
skills_dir = os.path.join(src, "skills")
third_party = []
for name in sorted(os.listdir(skills_dir)):
    path = os.path.join(skills_dir, name)
    if not os.path.isdir(path):
        continue
    if name == "synced":
        continue
    if os.path.exists(os.path.join(path, ".superset-managed")):
        third_party.append(f"`{name}`, installed and updated by the Superset app")
        continue
    if name.endswith("-workspace"):
        continue
    desc = skill_description(os.path.join(path, "SKILL.md"))
    w(f"- **{name}**: {desc}" if desc else f"- **{name}**")
w("")

synced = set()
synced_dir = os.path.join(skills_dir, "synced")
if os.path.isdir(synced_dir):
    for bucket in os.listdir(synced_dir):
        manifest = load(os.path.join(synced_dir, bucket, "manifest.json"), {})
        for skill in manifest.get("skills", []):
            synced.add(skill.get("name", skill.get("skillId", "?")))
if synced:
    third_party.append("synced from my claude.ai account: "
                       + ", ".join(f"`{s}`" for s in sorted(synced)))

w("### Skills installed by other tools (listed, not copied)")
w("")
for line in third_party:
    w(f"- {line}")
w("")

print("\n".join(out).rstrip() + "\n")
